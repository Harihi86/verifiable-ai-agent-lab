"""Runtime isolation harness for research tests against a disposable Herdr backend.

This module never touches the production Herdr installation under C:\\herdr.
It builds a scrubbed child environment, writes a fresh research config, and
invokes the verified workspace-local binary by absolute path.

Facts this harness relies on (Herdr v0.9.5 @ 2ecf19a9):
- src/config/io.rs:30-41  XDG_CONFIG_HOME / XDG_STATE_HOME win over APPDATA / LOCALAPPDATA on Windows.
- src/config/io.rs:22-28  app dir name is "herdr" (release) or "herdr-dev" (debug builds).
- docs socket-api "Socket paths": session resolution order is --session, HERDR_SOCKET_PATH, HERDR_SESSION, default.
- HERDR_CONFIG_PATH overrides the config file path (documented in cli-reference "Environment variables").
- src/config/model.rs defaults: update.version_check=true, update.manifest_check=true,
  session.resume_agents_on_restore=true, remote.manage_ssh_config=true, ui.toast.delivery=off.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import time
import uuid
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable, Mapping

WORKSPACE_ROOT = Path(r"C:\Herdr-dev")
RUNTIME_ROOT = WORKSPACE_ROOT / "runtime"
DEFAULT_BINARY = RUNTIME_ROOT / "bin" / "herdr-0.9.5" / "herdr.exe"
EXPECTED_BINARY_SHA256 = "cd877c8744296f4a38a2703bf13cf11728973649ec54959959c4587ffe5368b2"
APP_DIR_NAMES = ("herdr", "herdr-dev")

# Environment keys that must never leak from the calling shell into a research child process.
INHERITED_PREFIXES = ("HERDR_",)
INHERITED_EXACT = (
    "XDG_CONFIG_HOME",
    "XDG_STATE_HOME",
    "XDG_DATA_HOME",
    "XDG_CACHE_HOME",
)
# PATH entries that resolve a bare `herdr` to a production or pilot installation.
PRODUCTION_PATH_PATTERNS = (
    re.compile(r"[\\/]herdr[\\/]\.local[\\/]runtime", re.IGNORECASE),
    re.compile(r"<private-pilot-runtime>[\\/]runtime", re.IGNORECASE),
)

ISOLATED_CONFIG_TOML = """# Research-only Herdr configuration. Generated by prototypes/common/herdr_isolated.py.
# Automatic updates, remote manifest checks, SSH config management and agent
# restoration are disabled. No saved machines exist in this fresh XDG_CONFIG_HOME.

[update]
channel = "stable"
version_check = false
manifest_check = false

[remote]
manage_ssh_config = false

[session]
resume_agents_on_restore = false

[experimental]
allow_nested = true

[server]
headless_cols = 120
headless_rows = 40

[ui]
mouse_capture = false

[ui.toast]
delivery = "off"
"""


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def filter_path(path_value: str) -> str:
    entries = [p for p in path_value.split(os.pathsep) if p]
    kept = [p for p in entries if not any(pat.search(p) for pat in PRODUCTION_PATH_PATTERNS)]
    return os.pathsep.join(kept)


def scrubbed_env(base: Mapping[str, str] | None = None) -> dict[str, str]:
    """Return a copy of ``base`` without inherited Herdr/XDG context and production PATH entries."""
    source = dict(os.environ if base is None else base)
    cleaned: dict[str, str] = {}
    for key, value in source.items():
        upper = key.upper()
        if upper.startswith(INHERITED_PREFIXES):
            continue
        if upper in INHERITED_EXACT:
            continue
        if upper == "PATH":
            value = filter_path(value)
        cleaned[key] = value
    return cleaned


def unique_session_name(prefix: str = "ecc-research") -> str:
    stamp = time.strftime("%Y%m%d-%H%M%S")
    return f"{prefix}-{stamp}-{uuid.uuid4().hex[:6]}"


@dataclass
class IsolatedRuntime:
    """A disposable configuration/state/cache root plus a named Herdr session."""

    session_name: str = field(default_factory=unique_session_name)
    binary: Path = DEFAULT_BINARY
    root: Path | None = None
    extra_config_toml: str = ""

    def __post_init__(self) -> None:
        if self.root is None:
            self.root = RUNTIME_ROOT / "sessions" / self.session_name
        self.root = Path(self.root)
        self.binary = Path(self.binary)

    # -- layout -----------------------------------------------------------------
    @property
    def config_home(self) -> Path:
        return self.root / "xdg-config"

    @property
    def state_home(self) -> Path:
        return self.root / "xdg-state"

    @property
    def data_home(self) -> Path:
        return self.root / "xdg-data"

    @property
    def cache_home(self) -> Path:
        return self.root / "xdg-cache"

    @property
    def home_dir(self) -> Path:
        return self.root / "home"

    @property
    def tmp_dir(self) -> Path:
        return self.root / "tmp"

    @property
    def log_dir(self) -> Path:
        return self.root / "logs"

    @property
    def config_path(self) -> Path:
        return self.root / "herdr-research.toml"

    def herdr_config_dir(self, app_dir: str = "herdr") -> Path:
        return self.config_home / app_dir

    def herdr_state_dir(self, app_dir: str = "herdr") -> Path:
        return self.state_home / app_dir

    # -- preparation --------------------------------------------------------------
    def prepare(self) -> None:
        for directory in (
            self.config_home,
            self.state_home,
            self.data_home,
            self.cache_home,
            self.home_dir,
            self.tmp_dir,
            self.log_dir,
        ):
            directory.mkdir(parents=True, exist_ok=True)
        for app_dir in APP_DIR_NAMES:
            self.herdr_config_dir(app_dir).mkdir(parents=True, exist_ok=True)
            self.herdr_state_dir(app_dir).mkdir(parents=True, exist_ok=True)
        self.config_path.write_text(ISOLATED_CONFIG_TOML + self.extra_config_toml, encoding="utf-8")

    def env(self, base: Mapping[str, str] | None = None) -> dict[str, str]:
        env = scrubbed_env(base)
        env.update(
            {
                "XDG_CONFIG_HOME": str(self.config_home),
                "XDG_STATE_HOME": str(self.state_home),
                "XDG_DATA_HOME": str(self.data_home),
                "XDG_CACHE_HOME": str(self.cache_home),
                "HERDR_CONFIG_PATH": str(self.config_path),
                "HOME": str(self.home_dir),
                "TMP": str(self.tmp_dir),
                "TEMP": str(self.tmp_dir),
            }
        )
        return env

    def command(self, *args: str) -> list[str]:
        return [str(self.binary), "--session", self.session_name, *args]

    def resolution_record(self) -> dict:
        """Everything a reviewer needs to confirm isolation before a test runs."""
        return {
            "binary": str(self.binary),
            "binary_sha256": sha256_of(self.binary) if self.binary.exists() else None,
            "binary_sha256_expected": EXPECTED_BINARY_SHA256,
            "session_name": self.session_name,
            "config_path": str(self.config_path),
            "xdg_config_home": str(self.config_home),
            "xdg_state_home": str(self.state_home),
            "expected_config_dirs": [str(self.herdr_config_dir(a)) for a in APP_DIR_NAMES],
            "expected_state_dirs": [str(self.herdr_state_dir(a)) for a in APP_DIR_NAMES],
            "expected_session_dir": str(self.herdr_config_dir("herdr") / "sessions" / self.session_name),
            "home": str(self.home_dir),
            "tmp": str(self.tmp_dir),
            "scrubbed_keys": sorted(
                k for k in os.environ if k.upper().startswith(INHERITED_PREFIXES) or k.upper() in INHERITED_EXACT
            ),
            "path_entries_removed": [
                p
                for p in os.environ.get("PATH", "").split(os.pathsep)
                if any(pat.search(p) for pat in PRODUCTION_PATH_PATTERNS)
            ],
        }

    def write_resolution_record(self) -> Path:
        self.log_dir.mkdir(parents=True, exist_ok=True)
        target = self.log_dir / "resolution.json"
        target.write_text(json.dumps(self.resolution_record(), indent=2), encoding="utf-8")
        return target

    # -- execution ----------------------------------------------------------------
    def run(self, *args: str, timeout: float = 60.0, check: bool = False, input_text: str | None = None):
        if not self.binary.is_absolute():
            raise ValueError("binary must be an absolute path")
        argv = self.command(*args)
        completed = subprocess.run(
            argv,
            env=self.env(),
            cwd=str(self.tmp_dir),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
            input=input_text,
        )
        self._append_log("cli.log", argv, completed)
        if check and completed.returncode != 0:
            raise RuntimeError(f"herdr {' '.join(args)} failed ({completed.returncode}): {completed.stderr}")
        return completed

    def run_json(self, *args: str, timeout: float = 60.0):
        completed = self.run(*args, timeout=timeout)
        payload = None
        text = completed.stdout.strip() or completed.stderr.strip()
        if text:
            try:
                payload = json.loads(text)
            except json.JSONDecodeError:
                payload = None
        return completed, payload

    def start_server(self, extra_args: Iterable[str] = ()):
        self.log_dir.mkdir(parents=True, exist_ok=True)
        stdout = (self.log_dir / "server.stdout.log").open("ab")
        stderr = (self.log_dir / "server.stderr.log").open("ab")
        argv = self.command("server", *extra_args)
        process = subprocess.Popen(
            argv,
            env=self.env(),
            cwd=str(self.tmp_dir),
            stdin=subprocess.DEVNULL,
            stdout=stdout,
            stderr=stderr,
        )
        self._append_text("cli.log", f"$ {' '.join(argv)}  (pid {process.pid})\n")
        return process

    def wait_for_ping(self, timeout: float = 20.0, interval: float = 0.5) -> bool:
        """Poll a server-only command until it succeeds (workspace.list needs a live server)."""
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            completed = self.run("workspace", "list", timeout=10.0)
            if completed.returncode == 0:
                return True
            time.sleep(interval)
        return False

    def stop_server(self, process=None, timeout: float = 15.0) -> int | None:
        self.run("server", "stop", timeout=20.0)
        if process is None:
            return None
        try:
            return process.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            process.kill()
            return process.wait(timeout=5.0)

    # -- logging ------------------------------------------------------------------
    def _append_text(self, name: str, text: str) -> None:
        self.log_dir.mkdir(parents=True, exist_ok=True)
        with (self.log_dir / name).open("a", encoding="utf-8") as handle:
            handle.write(text)

    def _append_log(self, name: str, argv: list[str], completed) -> None:
        self._append_text(
            name,
            "$ "
            + " ".join(argv)
            + f"\nexit={completed.returncode}\n--- stdout ---\n{completed.stdout}\n--- stderr ---\n{completed.stderr}\n\n",
        )
